create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  user_number bigint generated by default as identity,
  username text not null,
  username_key text generated always as (lower(username)) stored,
  display_name text,
  note text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_length check (char_length(username) between 3 and 32),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9_]+$')
);

alter table public.profiles add column if not exists user_number bigint generated by default as identity;

create unique index if not exists profiles_user_number_unique on public.profiles (user_number);

create unique index if not exists profiles_username_key_unique
on public.profiles (username_key);

with ordered_profiles as (
  select id,row_number() over(order by created_at asc,id asc) as number
  from public.profiles
)
update public.profiles as profiles
set user_number=ordered_profiles.number
from ordered_profiles
where profiles.id=ordered_profiles.id;

select setval(
 pg_get_serial_sequence('public.profiles','user_number'),
 greatest(coalesce((select max(user_number) from public.profiles),1),1),
 coalesce((select max(user_number) from public.profiles),0)>0
);

