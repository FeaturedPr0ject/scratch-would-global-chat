create or replace function public.save_username_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.username_history (
      username_key,
      username,
      profile_id
    )
    values (
      lower(new.username),
      new.username,
      new.id
    )
    on conflict (username_key) do nothing;
    return new;
  end if;

  if tg_op = 'UPDATE' and old.username_key <> new.username_key then
    insert into public.username_history (
      username_key,
      username,
      profile_id
    )
    values (
      old.username_key,
      old.username,
      old.id
    )
    on conflict (username_key) do nothing;

    insert into public.username_history (
      username_key,
      username,
      profile_id
    )
    values (
      new.username_key,
      new.username,
      new.id
    )
    on conflict (username_key) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists profiles_username_history on public.profiles;

create trigger profiles_username_history
after insert or update of username on public.profiles
for each row
execute function public.save_username_history();

create or replace function public.create_friendship_after_accept()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'accepted' and old.status <> 'accepted' then
    insert into public.friendships (
      user_a,
      user_b
    )
    values (
      new.requester_id,
      new.recipient_id
    )
    on conflict do nothing;
  end if;

  return new;
end;
$$;

